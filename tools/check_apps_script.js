/**
 * Проверка эталонного скрипта для Таблиц без самих Таблиц.
 *
 * Читает ту же выгрузку, что участник открывает в Google Таблицах, прогоняет
 * через функции скрипта и сверяет результат с ожидаемым.
 *
 *     node tools/check_apps_script.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const скрипт = require(path.join(ROOT, '2.5_кейс_карточный_бизнес/2.5.6_эталон_google_apps_script.gs'));

// --- читаем выгрузку так же, как её видит редактор таблиц -----------------
const текст = fs.readFileSync(path.join(ROOT, 'data/cards/cards_issued_raw.csv'), 'utf8')
  .replace(/^﻿/, '');
const строкиФайла = текст.trim().split(/\r?\n/).map((s) => s.split(';'));
const заголовки = строкиФайла[0];
const данные = строкиФайла.slice(1);

console.log(`Строк в выгрузке: ${данные.length}`);

const очищенные = скрипт.очиститьСтроки(данные);
console.log(`После удаления повторов: ${очищенные.length}`);

const поКаналам = скрипт.свести(очищенные, скрипт.СТОЛБЕЦ.канал);
const поТарифам = скрипт.свести(очищенные, скрипт.СТОЛБЕЦ.тариф);

console.log('\nДоля активации по каналам:');
поКаналам.forEach((r) => console.log(`  ${r[0].padEnd(22)} ${String(r[2]).padStart(5)}/${String(r[1]).padStart(5)} = ${r[3]} %`));
console.log('Доля активации по тарифам:');
поТарифам.forEach((r) => console.log(`  ${r[0].padEnd(22)} ${String(r[2]).padStart(5)}/${String(r[1]).padStart(5)} = ${r[3]} %`));

// --- сверка с ожидаемым ---------------------------------------------------
const ожидание = {
  строк: 2400,
  каналы: {
    'Мобильное приложение': [813, 625],
    'Отделение': [768, 489],
    'Сайт банка': [386, 231],
    'Партнёрская сеть': [433, 164],
  },
};

const провалы = [];
if (очищенные.length !== ожидание.строк) {
  провалы.push(`после чистки ${очищенные.length} строк вместо ${ожидание.строк}`);
}
if (поКаналам.length !== 4) провалы.push(`каналов ${поКаналам.length} вместо 4`);
поКаналам.forEach(([имя, всего, активных]) => {
  const ждём = ожидание.каналы[имя];
  if (!ждём) return провалы.push(`неизвестный канал «${имя}»`);
  if (всего !== ждём[0] || активных !== ждём[1]) {
    провалы.push(`«${имя}»: ${активных}/${всего} вместо ${ждём[1]}/${ждём[0]}`);
  }
});

// частные случаи разбора значений
const проверки = [
  ['ОТДЕЛЕНИЕ ', 'Отделение'], ['Партнерская сеть', 'Партнёрская сеть'],
  ['МП', 'Мобильное приложение'], ['Веб-сайт', 'Сайт банка'],
];
проверки.forEach(([вход, ждём]) => {
  const факт = скрипт.нормализоватьКанал(вход);
  if (факт !== ждём) провалы.push(`канал «${вход}» → «${факт}», ожидалось «${ждём}»`);
});
[['12 000', 12000], ['12000,50', 12000.5], ['12000.5', 12000.5], ['', null], ['н/д', null]]
  .forEach(([вход, ждём]) => {
    const факт = скрипт.разобратьЧисло(вход);
    if (факт !== ждём) провалы.push(`сумма «${вход}» → ${факт}, ожидалось ${ждём}`);
  });
[['15.03.2025', '2025-03-15'], ['2025-03-15', '2025-03-15']].forEach(([вход, ждём]) => {
  const d = скрипт.разобратьДату(вход);
  const факт = d && `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  if (факт !== ждём) провалы.push(`дата «${вход}» → ${факт}, ожидалось ${ждём}`);
});

console.log('');
if (провалы.length) {
  провалы.forEach((p) => console.log(`  ✗ ${p}`));
  process.exit(1);
}
console.log('Проверка пройдена: скрипт даёт ожидаемые числа.');
